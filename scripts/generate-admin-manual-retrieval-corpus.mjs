import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const SOURCE_PATHS = [
  "README.md",
  "vercel.json",
  "package.json",
  "next.config.ts",
  "docs/ACCOUNT-OS-ROLLOUT-PR.md",
  "docs/ENABLE-REAL-AI.md",
  "docs/PAYMENT-PREFERENCES.md",
  "prisma/schema.postgresql.prisma",
  "scripts/prisma-prepare.mjs",
  "src/lib/admin-auth.ts",
  "src/lib/admin-manual-store.ts",
  "src/lib/audit-log.ts",
  "src/app/admin/manual/page.tsx",
  "src/app/api/admin/manual-assistant/route.ts",
  "src/app/api/admin/payments/route.ts",
  "src/app/api/admin/stripe/webhook/route.ts",
  "src/app/api/auth/start/route.ts",
  "src/components/chatbot/chatbot-provider.tsx",
];

const OUTPUT_PATH = "src/lib/admin-manual-retrieval-corpus.ts";
const MAX_CHUNKS_PER_FILE = 6;
const MIN_CHUNK_LENGTH = 120;
const MAX_CHUNK_LENGTH = 1000;

function compact(text) {
  return text.replace(/\r/g, "").replace(/\t/g, "  ").replace(/\s+/g, " ").trim();
}

function splitChunks(rawText) {
  const normalized = rawText.replace(/\r/g, "");
  const rawChunks = normalized
    .split(/\n\n+/)
    .map((chunk) => compact(chunk))
    .filter((chunk) => chunk.length >= MIN_CHUNK_LENGTH)
    .slice(0, MAX_CHUNKS_PER_FILE * 2);

  return rawChunks
    .map((chunk) => chunk.slice(0, MAX_CHUNK_LENGTH))
    .slice(0, MAX_CHUNKS_PER_FILE);
}

async function buildCorpus() {
  const corpus = [];

  for (const relativePath of SOURCE_PATHS) {
    try {
      const absolutePath = path.join(process.cwd(), relativePath);
      const text = await readFile(absolutePath, "utf8");
      const chunks = splitChunks(text);

      chunks.forEach((chunk, index) => {
        corpus.push({
          id: `${relativePath}#${index + 1}`,
          path: relativePath,
          title: path.basename(relativePath),
          text: chunk,
        });
      });
    } catch {
      // Skip missing files for robustness across environments.
    }
  }

  return corpus;
}

function toTsModule(corpus) {
  const payload = JSON.stringify(corpus, null, 2);

  return [
    "/* AUTO-GENERATED FILE. DO NOT EDIT DIRECTLY. */",
    "/* Generated by scripts/generate-admin-manual-retrieval-corpus.mjs */",
    "",
    "export type AdminManualRetrievalChunk = {",
    "  id: string;",
    "  path: string;",
    "  title: string;",
    "  text: string;",
    "};",
    "",
    `export const retrievalCorpus: AdminManualRetrievalChunk[] = ${payload};`,
    "",
  ].join("\n");
}

async function main() {
  const corpus = await buildCorpus();
  const moduleText = toTsModule(corpus);
  const outputPath = path.join(process.cwd(), OUTPUT_PATH);

  await writeFile(outputPath, moduleText, "utf8");
  console.log(`[manual-corpus] Generated ${corpus.length} chunks at ${OUTPUT_PATH}`);
}

main().catch((error) => {
  console.error("[manual-corpus] Generation failed", error);
  process.exitCode = 1;
});
